# Assignment 1: Practice with Fathers's Information
name = "Faheem Khan"
age = 50
salary = 75000.50
is_employed = True

print("Father Information")

# sep()
print("Name", "Age", "Salary", sep=" | ")

# end()
print("My father's name is", end=": ")
print(name)

# Comma formatting
print("Name:", name, "Age:", age)

# Plus formatting
print("My father's name is " + name)

# f-string formatting
print(f"My father is {age} years old.")

# type()
print(type(name))
print(type(age))
print(type(salary))
print(type(is_employed))

# Display all information
print(f"Name: {name}, Age: {age}, Salary: {salary}, Employed: {is_employed}")


